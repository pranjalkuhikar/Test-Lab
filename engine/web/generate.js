// Playwright test files for a hosted website, built from what the crawl observed. Read-only: tests navigate and read, they never submit forms.
import { SCHEMA_HELPER, infer } from "../generate/contract.js";
import path from "node:path";
import { header, q, slug } from "../generate/util.js";

const H = (title, lines = []) => header(title, ["Generated from a read-only analysis of " + "the live site. Failing tests point at real problems (or at a test that needs adjusting).", ...lines]);

export const PAGE_HELPER = `// Helpers shared by the generated website tests.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);

// collects JavaScript errors and failed same-origin requests while a page is used
export function watch(page) {
  const problems = [];
  page.on("pageerror", (e) => problems.push("page error: " + e.message));
  page.on("console", (m) => { if (m.type() === "error" && !/favicon|Failed to load resource/i.test(m.text())) problems.push("console: " + m.text().slice(0, 160)); });
  page.on("response", (r) => { try { if (r.status() >= 400 && new URL(r.url()).origin === new URL(page.url() === "about:blank" ? r.url() : page.url()).origin) problems.push("HTTP " + r.status() + " " + r.url().slice(0, 100)); } catch {} });
  return problems;
}

// runs axe-core (the accessibility engine) inside the page
export async function runAxe(page) {
  const axe = require("axe-core");
  await page.addScriptTag({ content: axe.source });
  return page.evaluate(async () => (await window.axe.run({ resultTypes: ["violations"] })).violations.map((v) => ({ id: v.id, impact: v.impact, help: v.help, count: v.nodes.length, example: v.nodes[0]?.target?.[0] || "" })));
}
`;

const PROJECTS = (site) => `// Playwright configuration generated by TestLab.
//   npm install            (installs @playwright/test and axe-core)
//   npx playwright install chromium     (or set PLAYWRIGHT_EXECUTABLE to a local Chrome/Brave)
//   BASE_URL=${site.origin} npx playwright test
// The first run of visual.spec.mjs needs baselines:  npx playwright test visual --update-snapshots
import { defineConfig, devices } from "@playwright/test";
const launchOptions = process.env.PLAYWRIGHT_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE } : {};
export default defineConfig({
  testDir: ".",
  testMatch: /.*\\.spec\\.mjs/,
  timeout: 45_000,
  retries: 1,
  workers: 1, // one page at a time: gentle on a live site
  expect: { toHaveScreenshot: { maxDiffPixelRatio: 0.02 } },
  use: { baseURL: process.env.BASE_URL || ${q(site.origin)}, trace: "retain-on-failure", launchOptions },
  projects: [
    { name: "desktop", use: { viewport: { width: 1280, height: 800 } } },
    { name: "mobile", use: { ...devices["Pixel 7"], launchOptions }, testMatch: /(smoke|visual)\\.spec\\.mjs/ },
  ],
});
`;

export function siteFiles(site, an, rec, layers = null) {
  const pages = site.pages.filter((p) => !p.blocked && !p.error && p.status && p.status < 400);
  if (!pages.length) return { files: [], count: 0, skipped: [{ layer: "all", what: "pages", reason: "no page could be analysed" }] };
  const files = [], skipped = [];
  const add = (p, layer, content, tests) => files.push({ path: path.posix.normalize(`site-tests/${p}`), layer, content, tests, ...(tests ? {} : { support: true }) });
  const paths = pages.map((p) => new URL(p.url).pathname + new URL(p.url).search).slice(0, 12);
  const limit = (id) => (layers ? layers.includes(id) : rec.mix.find((m) => m.id === id)?.percent > 0);
  let count = 0;

  // ---- smoke (+ mobile overflow)
  if (limit("e2e")) {
    const l = [H("Smoke tests: every page loads cleanly"), 'import { test, expect } from "@playwright/test";', 'import { watch } from "../helpers/page.mjs";', "", `const PAGES = ${JSON.stringify(paths)};`, "",
      "for (const path of PAGES) {",
      '  test(path + " loads without errors", async ({ page }) => {',
      "    const problems = watch(page);",
      '    const res = await page.goto(path, { waitUntil: "networkidle" });',
      '    expect(res?.status() ?? 0, "HTTP status").toBeLessThan(400);',
      "    await expect(page).toHaveTitle(/.+/);",
      '    await expect(page.locator("body")).toBeVisible();',
      '    expect(problems, problems.join("\\n")).toEqual([]);',
      "  });", "",
      '  test(path + " fits the screen (no sideways scrolling)", async ({ page }) => {',
      '    await page.goto(path, { waitUntil: "networkidle" });',
      "    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);",
      '    expect(overflow, "content is wider than the screen by " + overflow + "px").toBeLessThanOrEqual(2);',
      "  });", "}", "",
      'test("an unknown address returns a real 404", async ({ request }) => {',
      '  const res = await request.get("/testlab-does-not-exist-" + Date.now());',
      "  expect(res.status()).toBe(404);", "});", ""];
    if (an.profile.forms) { /* forms are covered in forms.spec */ }
    add("smoke.spec.mjs", "e2e", l.join("\n"), paths.length * 2 * 2 + 1); count += paths.length * 2 * 2 + 1; // desktop + mobile
  } else skipped.push({ layer: "e2e", what: "smoke", reason: "not recommended for this site" });

  // ---- links
  const internal = [...new Set(pages.flatMap((p) => (p.links || []).map((l) => (l.href || "").split("#")[0]).filter((u) => u.startsWith(site.origin) && !/\.(pdf|zip|png|jpe?g|svg|webp|gif|mp4)$/i.test(u))))].slice(0, 60);
  if (limit("links") && internal.length) {
    add("links.spec.mjs", "links", [H("Links: every internal link works"), 'import { test, expect } from "@playwright/test";', "", `const LINKS = ${JSON.stringify(internal.map((u) => u.replace(site.origin, "") || "/"), null, 0)};`, "",
      'test("all internal links respond without errors", async ({ request }) => {',
      "  for (const link of LINKS) {",
      '    const res = await request.get(link, { maxRedirects: 5 });',
      '    expect.soft(res.status(), link).toBeLessThan(400);',
      "  }", "});", ""].join("\n"), 1); count += 1;
  }

  // ---- accessibility
  if (limit("a11y")) {
    add("a11y.spec.mjs", "a11y", [H("Accessibility (axe-core)", ["Fails on serious and critical violations. Change FAIL_ON to also include 'moderate' once those are fixed."]), 'import { test, expect } from "@playwright/test";', 'import { runAxe } from "../helpers/page.mjs";', "",
      'const FAIL_ON = ["serious", "critical"];', `const PAGES = ${JSON.stringify(paths)};`, "",
      "for (const path of PAGES) {",
      '  test(path + " has no serious accessibility violations", async ({ page }) => {',
      '    await page.goto(path, { waitUntil: "networkidle" });',
      "    const violations = (await runAxe(page)).filter((v) => FAIL_ON.includes(v.impact));",
      '    expect(violations.map((v) => v.impact + ": " + v.help + " (" + v.count + " elements, e.g. " + v.example + ")"), "accessibility violations").toEqual([]);',
      "  });", "}", ""].join("\n"), paths.length); count += paths.length;
  }

  // ---- SEO
  if (limit("seo")) {
    add("seo.spec.mjs", "seo", [H("SEO and metadata"), 'import { test, expect } from "@playwright/test";', "", `const PAGES = ${JSON.stringify(paths)};`, "",
      "for (const path of PAGES) {",
      '  test(path + " has complete metadata", async ({ page }) => {',
      '    await page.goto(path, { waitUntil: "domcontentloaded" });',
      "    const m = await page.evaluate(() => ({",
      "      title: document.title, lang: document.documentElement.lang,",
      '      description: document.querySelector(\'meta[name="description"]\')?.content || "",',
      '      viewport: !!document.querySelector(\'meta[name="viewport"]\'),',
      '      canonical: document.querySelector(\'link[rel="canonical"]\')?.href || "",',
      '      ogTitle: !!document.querySelector(\'meta[property="og:title"]\'), ogImage: !!document.querySelector(\'meta[property="og:image"]\'),',
      '      h1: document.querySelectorAll("h1").length,',
      "      imagesWithoutAlt: [...document.images].filter((i) => !i.hasAttribute(\"alt\")).length,",
      "    }));",
      '    expect.soft(m.title.length, "title length").toBeGreaterThanOrEqual(10);',
      '    expect.soft(m.title.length, "title length").toBeLessThanOrEqual(70);',
      '    expect.soft(m.description.length, "meta description length (50-160)").toBeGreaterThanOrEqual(50);',
      '    expect.soft(m.description.length, "meta description length (50-160)").toBeLessThanOrEqual(160);',
      '    expect.soft(m.h1, "number of <h1>").toBe(1);',
      '    expect.soft(m.lang, "<html lang>").not.toBe("");',
      '    expect.soft(m.viewport, "viewport meta tag").toBe(true);',
      '    expect.soft(m.canonical, "canonical link").not.toBe("");',
      '    expect.soft(m.ogTitle && m.ogImage, "Open Graph title and image").toBe(true);',
      '    expect.soft(m.imagesWithoutAlt, "images without alt").toBe(0);',
      "  });", "}", "",
      'test("sitemap.xml and robots.txt exist", async ({ request }) => {',
      '  expect.soft((await request.get("/sitemap.xml")).status(), "sitemap.xml").toBe(200);',
      '  expect.soft((await request.get("/robots.txt")).status(), "robots.txt").toBe(200);', "});", ""].join("\n"), paths.length + 1); count += paths.length + 1;
  }

  // ---- security headers (passive)
  if (limit("security")) {
    add("security-headers.spec.mjs", "security", [H("Security headers (passive: reads what the site already sends)"), 'import { test, expect } from "@playwright/test";', "",
      'test("home page sends the recommended security headers", async ({ request, baseURL }) => {',
      '  const res = await request.get("/");',
      "  const h = res.headers();",
      '  if (baseURL.startsWith("https:")) expect.soft(h["strict-transport-security"], "Strict-Transport-Security (HSTS)").toBeTruthy();',
      '  expect.soft(h["x-content-type-options"], "X-Content-Type-Options: nosniff").toBe("nosniff");',
      '  expect.soft(h["referrer-policy"], "Referrer-Policy").toBeTruthy();',
      '  expect.soft(h["x-frame-options"] || /frame-ancestors/.test(h["content-security-policy"] || ""), "clickjacking protection (X-Frame-Options or CSP frame-ancestors)").toBeTruthy();',
      '  expect.soft(h["content-security-policy"], "Content-Security-Policy").toBeTruthy();',
      '  expect.soft(h["x-powered-by"], "X-Powered-By should not reveal the technology").toBeFalsy();', "});", "",
      ...(site.checks.https ? ['test("http:// redirects to https://", async ({ playwright, baseURL }) => {', '  const ctx = await playwright.request.newContext({ maxRedirects: 0 });', '  const res = await ctx.get(baseURL.replace("https:", "http:") + "/");', "  expect([301, 302, 307, 308]).toContain(res.status());", '  expect(res.headers()["location"] || "").toMatch(/^https:/);', "  await ctx.dispose();", "});", ""] : []),
    ].join("\n"), site.checks.https ? 2 : 1); count += site.checks.https ? 2 : 1;
  }

  // ---- performance: a regression guard from today's numbers + "good" thresholds as soft checks
  if (limit("perf")) {
    const perfPages = pages.slice(0, 5);
    const budgets = perfPages.map((p) => ({ path: new URL(p.url).pathname, lcp: Math.max(Math.round((p.vitals?.lcp || 2000) * 1.5), 2500), load: Math.max(Math.round((p.timing?.load || 2000) * 1.5), 4000), kb: Math.max(Math.round((p.timing?.transferKB || 500) * 1.5 + 200), 800) }));
    add("performance.spec.mjs", "perf", [H("Performance budgets", ["Hard limits = 1.5x what was measured when these tests were generated (a regression guard). Soft checks use Google's 'good' Web Vitals thresholds."]), 'import { test, expect } from "@playwright/test";', "", `const BUDGETS = ${JSON.stringify(budgets, null, 2)};`, "",
      "for (const b of BUDGETS) {",
      '  test(b.path + " stays within its performance budget", async ({ page }) => {',
      '    await page.goto(b.path, { waitUntil: "networkidle" });',
      "    const m = await page.evaluate(() => new Promise((resolve) => {",
      '      const out = { lcp: 0, cls: 0 };',
      '      new PerformanceObserver((l) => { for (const e of l.getEntries()) out.lcp = e.startTime; }).observe({ type: "largest-contentful-paint", buffered: true });',
      '      new PerformanceObserver((l) => { for (const e of l.getEntries()) if (!e.hadRecentInput) out.cls += e.value; }).observe({ type: "layout-shift", buffered: true });',
      '      const nav = performance.getEntriesByType("navigation")[0];',
      '      const kb = performance.getEntriesByType("resource").reduce((a, r) => a + (r.encodedBodySize || 0), nav.encodedBodySize || 0) / 1024;',
      "      setTimeout(() => resolve({ ...out, load: nav.loadEventEnd, kb }), 900);",
      "    }));",
      '    expect(m.lcp, "largest contentful paint (ms), budget " + b.lcp).toBeLessThan(b.lcp);',
      '    expect(m.load, "load event (ms), budget " + b.load).toBeLessThan(b.load);',
      '    expect(m.kb, "transferred KB, budget " + b.kb).toBeLessThan(b.kb);',
      '    expect.soft(m.lcp, "LCP should be under 2500 ms (good)").toBeLessThan(2500);',
      '    expect.soft(m.cls, "CLS should be under 0.1 (good)").toBeLessThan(0.1);',
      "  });", "}", ""].join("\n"), budgets.length); count += budgets.length;
  }

  // ---- visual (desktop + mobile)
  if (limit("visual")) {
    const vp = paths.slice(0, 6);
    add("visual.spec.mjs", "visual", [H("Visual regression (desktop and mobile)", ["First run: npx playwright test visual --update-snapshots  (creates the baseline images), then run normally to compare."]), 'import { test, expect } from "@playwright/test";', "", `const PAGES = ${JSON.stringify(vp)};`, "",
      "for (const path of PAGES) {",
      '  test(path + " looks the same", async ({ page }, info) => {',
      '    await page.goto(path, { waitUntil: "networkidle" });',
      "    await page.waitForTimeout(500);",
      '    await expect(page).toHaveScreenshot((path === "/" ? "home" : path.replace(/[^a-z0-9]+/gi, "-")) + ".png", { fullPage: true, animations: "disabled", caret: "hide" });',
      "  });", "}", ""].join("\n"), vp.length * 2); count += vp.length * 2;
  }

  // ---- forms (read-only: they are NOT submitted on a live site)
  const forms = pages.flatMap((p) => (p.forms || []).map((f) => ({ path: new URL(p.url).pathname, ...f })));
  if (forms.length && limit("e2e")) {
    add("forms.spec.mjs", "e2e", [H("Forms render and are usable", ["These tests do NOT submit forms: submitting on a live site can create real data or send real e-mail."]), 'import { test, expect } from "@playwright/test";', "", `const FORMS = ${JSON.stringify(forms.map((f) => ({ path: f.path, fields: f.fields.map((x) => ({ name: x.name, type: x.type })) })), null, 0)};`, "",
      "for (const [i, f] of FORMS.entries()) {",
      '  test("form " + (i + 1) + " on " + f.path + " is present and its fields are labelled", async ({ page }) => {',
      "    await page.goto(f.path);",
      "    for (const field of f.fields) {",
      '      const el = page.locator("[name=\\"" + field.name + "\\"], #" + field.name).first();',
      "      await expect(el, field.name).toBeVisible();",
      "      const named = await el.evaluate((n) => !!(n.getAttribute(\"aria-label\") || n.getAttribute(\"aria-labelledby\") || n.labels?.length || n.placeholder));",
      '      expect.soft(named, field.name + " needs a label, aria-label or placeholder").toBe(true);',
      "    }", "  });", "}", ""].join("\n"), forms.length); count += forms.length;
  } else if (limit("e2e")) skipped.push({ layer: "e2e", what: "forms", reason: "no forms were found on the crawled pages" });

  // ---- API contract (same-origin JSON the pages fetch)
  const apis = site.apis.filter((a) => a.sameOrigin && a.method === "GET" && a.sample !== undefined);
  if (limit("contract") && apis.length) {
    add("api-contract.spec.mjs", "contract", [H("API contract: the JSON the pages fetch keeps its shape"), 'import { test, expect } from "@playwright/test";', 'import { validate } from "../helpers/schema.mjs";', "",
      ...apis.map((a) => `test(${q("GET " + new URL(a.url).pathname)}, async ({ request }) => {\n  const res = await request.get(${q(a.url.replace(site.origin, ""))});\n  expect(res.status()).toBe(${a.status});\n  const errors = validate(await res.json(), ${JSON.stringify(infer(a.sample))});\n  expect(errors, errors.join("\\n")).toEqual([]);\n});\n`)].join("\n"), apis.length); count += apis.length;
    add("../helpers/schema.mjs", "support", SCHEMA_HELPER, 0);
  } else if (limit("contract")) skipped.push({ layer: "contract", what: "API contract", reason: "no same-origin JSON calls were captured" });

  // ---- support files
  add("../helpers/page.mjs", "support", PAGE_HELPER, 0);
  add("playwright.config.mjs", "support", PROJECTS(site), 0);
  add("../package.json", "support", JSON.stringify({ name: "site-tests", private: true, type: "module", scripts: { test: "playwright test", "test:update-snapshots": "playwright test visual --update-snapshots" }, devDependencies: { "@playwright/test": "^1.65.0", "axe-core": "^4.11.0" } }, null, 2), 0);
  add("../README.md", "support", `# Website tests for ${site.host}

Generated by **TestLab** from a read-only visit of ${site.url}. Failing tests usually point at **real problems** on the site (or at a check that needs adjusting).

\`\`\`bash
npm install
npx playwright install chromium          # or: PLAYWRIGHT_EXECUTABLE="/path/to/Chrome-or-Brave"
npx playwright test --config site-tests/playwright.config.mjs visual --update-snapshots   # first run only: creates visual baselines
npx playwright test --config site-tests/playwright.config.mjs
\`\`\`

| File | What it checks |
|---|---|
| \`smoke.spec.mjs\` | every page loads, no console/network errors, no sideways scrolling (desktop and mobile), real 404s |
| \`links.spec.mjs\` | internal links resolve |
| \`a11y.spec.mjs\` | accessibility with axe-core (serious and critical fail) |
| \`seo.spec.mjs\` | title, description, headings, lang, canonical, Open Graph, alt text, sitemap/robots |
| \`security-headers.spec.mjs\` | recommended response headers (passive) |
| \`performance.spec.mjs\` | regression budgets (1.5x today's numbers) plus Google's "good" thresholds |
| \`visual.spec.mjs\` | full-page screenshots, desktop and mobile |
| \`forms.spec.mjs\` | forms exist and fields are labelled (**never submitted**) |

Only run these against sites you own or have permission to test.
`, 0);
  return { files, count, skipped };
}
