// End-to-end tests with Playwright: a real browser opens each page and exercises its forms.
// Kept deliberately small: E2E is slow and brittle, so it covers "does every page load without errors" and "do forms accept input".
import { header, q, slug, sampleFor } from "./util.js";

export const PLAYWRIGHT_CONFIG = `// Playwright configuration generated by TestLab.
//   npm i -D @playwright/test && npx playwright install chromium
//   BASE_URL=http://localhost:3000 npx playwright test --config e2e/playwright.config.mjs
import { defineConfig } from "@playwright/test";
export default defineConfig({
  testDir: ".",
  testMatch: /.*\\.spec\\.mjs/,
  timeout: 30_000,
  retries: 1,
  use: {
    baseURL: process.env.BASE_URL || "__BASE_URL__", trace: "retain-on-failure", screenshot: "only-on-failure",
    // use an installed browser instead of downloading one: PLAYWRIGHT_EXECUTABLE=/path/to/chrome-or-brave
    launchOptions: process.env.PLAYWRIGHT_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE } : {},
  },
});
`;

const safeRe = (s) => String(s).replace(/[.*+?^${}()|[\]\\/]/g, "\\$&").slice(0, 60);

export function e2eFiles(model) {
  const pages = model.pages.filter((p) => !p.dynamic);
  if (!pages.length) return { files: [], count: 0 };
  let count = 0;
  const out = [header("End-to-end: every page loads cleanly", ["Requires Playwright (see playwright.config.mjs). Not run automatically by TestLab."]), 'import { test, expect } from "@playwright/test";', "",
    "// collects JavaScript errors and failed requests while a page is used",
    "function watch(page) {", "  const problems = [];", '  page.on("pageerror", (e) => problems.push("page error: " + e.message));', '  page.on("console", (m) => { if (m.type() === "error" && !/favicon|Failed to load resource/i.test(m.text())) problems.push("console: " + m.text()); });', "  return problems;", "}", ""];
  for (const p of pages) {
    out.push(`test.describe(${q(`page ${p.path}`)}, () => {`);
    out.push(`  test("loads without errors", async ({ page }) => {\n    const problems = watch(page);\n    const res = await page.goto(${q(p.path)});\n    expect(res?.status() ?? 0, "page status").toBeLessThan(400);\n    await expect(page.locator("body")).toBeVisible();\n${p.headings[0] ? `    await expect(page.getByRole("heading", { name: new RegExp(${q(safeRe(p.headings[0]))}, "i") }).first()).toBeVisible();\n` : ""}    expect(problems, problems.join("\\n")).toEqual([]);\n  });`);
    count++;
    if (p.hasForm && p.inputs.length) {
      const named = p.inputs.filter((i) => i.name || i.placeholder).slice(0, 6);
      const button = p.buttons.find((b) => /add|save|submit|create|sign|log|register|send|post/i.test(b)) || p.buttons[0];
      out.push(`  test("form accepts input and submits without errors", async ({ page }) => {\n    const problems = watch(page);\n    await page.goto(${q(p.path)});\n${named.map((i) => {
        const val = i.type === "email" ? "testlab@example.com" : i.type === "password" ? "Sup3r-secret-pass!" : i.type === "number" ? "5" : i.type === "checkbox" ? null : sampleFor(i.name || i.placeholder || "text");
        const loc = i.name ? `page.locator('[name="${i.name}"]')` : `page.getByPlaceholder(${q(i.placeholder)})`;
        return val === null ? `    await ${loc}.check();` : `    await ${loc}.fill(${q(val)});`;
      }).join("\n")}\n${button ? `    await page.getByRole("button", { name: new RegExp(${q(safeRe(button))}, "i") }).first().click();\n` : `    await page.keyboard.press("Enter");\n`}    await page.waitForLoadState("networkidle");\n    expect(problems, problems.join("\\n")).toEqual([]);\n  });`);
      out.push(`  test("empty form submission does not crash the page", async ({ page }) => {\n    const problems = watch(page);\n    await page.goto(${q(p.path)});\n${button ? `    await page.getByRole("button", { name: new RegExp(${q(safeRe(button))}, "i") }).first().click();\n` : `    await page.keyboard.press("Enter");\n`}    await page.waitForTimeout(500);\n    await expect(page.locator("body")).toBeVisible();\n    expect(problems, problems.join("\\n")).toEqual([]);\n  });`);
      count += 2;
    }
    out.push("});", "");
  }
  const files = [{ path: "e2e/pages.spec.mjs", layer: "e2e", content: out.join("\n"), tests: count }];
  return { files, count };
}
