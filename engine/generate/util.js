// Shared bits for the generators: runner flavours (node:test or Vitest), naming, file headers, sample data.
export const q = (s) => JSON.stringify(String(s));
export const slug = (s) => String(s).replace(/\.[a-z]+$/i, "").replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-+|-+$/g, "").toLowerCase() || "root";
export const envName = (s) => String(s).toUpperCase().replace(/[^A-Z0-9]+/g, "_");

export function flavor(name) {
  const vitest = name === "vitest";
  return {
    name: vitest ? "vitest" : "node",
    imports: vitest ? 'import { describe, it, expect } from "vitest";' : 'import { describe, it } from "node:test";\nimport assert from "node:assert/strict";',
    eq: (a, b) => (vitest ? `expect(${a}).toBe(${b});` : `assert.equal(${a}, ${b});`),
    deep: (a, b) => (vitest ? `expect(${a}).toStrictEqual(${b});` : `assert.deepStrictEqual(${a}, ${b});`),
    ok: (cond, msg) => (vitest ? `expect(${cond}, ${msg}).toBeTruthy();` : `assert.ok(${cond}, ${msg});`),
    // it(name, body) with an optional "skip when" expression
    it: (name, body, { skip } = {}) => {
      const indented = body.split("\n").map((l) => "    " + l).join("\n");
      if (skip) return vitest ? `  it.skipIf(${skip})(${q(name)}, async () => {\n${indented}\n  });` : `  it(${q(name)}, { skip: ${skip} }, async () => {\n${indented}\n  });`;
      return `  it(${q(name)}, async () => {\n${indented}\n  });`;
    },
  };
}

export const header = (title, lines = []) => `// ──────────────────────────────────────────────────────────────────────────
// ${title}
// AUTO-GENERATED by TestLab. Review before trusting: tests describe what the code
// does today or what it should plausibly do, and a human has to confirm that is right.
${lines.map((l) => "// " + l).join("\n")}${lines.length ? "\n" : ""}// ──────────────────────────────────────────────────────────────────────────`;

export const sampleFor = (f) => (/title|name|text|label|desc/i.test(f) ? "TestLab sample" : /done|is_|has_|enabled|active|flag|completed/i.test(f) ? false : /id$/i.test(f) ? 1 : /count|limit|offset|age|total|qty/i.test(f) ? 3 : /email/i.test(f) ? "testlab@example.com" : /password/i.test(f) ? "Sup3r-secret-pass!" : "sample");
export const bodyLiteral = (fields, extra = {}) => `{ ${[...fields.map((f) => `${/^[A-Za-z_$][\w$]*$/.test(f) ? f : q(f)}: ${JSON.stringify(sampleFor(f))}`), ...Object.entries(extra).map(([k, v]) => `${k}: ${JSON.stringify(v)}`)].join(", ")} }`;
// "/api/todos/:id" → `/api/todos/${id}` using a JS template string
export const pathTemplate = (p, vars = {}) => "`" + p.replace(/:(\w+)\*?/g, (_, n) => "${" + (vars[n] ?? "id") + "}") + "`";
